#!/usr/bin/env python3
"""Generate rvfi_reference.svh from hvl/common/rvfi_reference.json.

Each JSON entry  "sig[ch]" : "<hierarchical expression>"  becomes
    assign mon_itf.sig[ch] = <hierarchical expression>;
The file is `include`d by top_tb.svh to connect the DUT commit port to the
RVFI monitor.
"""

import json
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_rvfi_ref.py <rvfi_reference.json> <out.svh>")
    with open(sys.argv[1]) as f:
        ref = json.load(f)
    with open(sys.argv[2], "w", newline="\n") as f:
        f.write("// Auto-generated by tools/xsim/gen_rvfi_ref.py -- do not edit\n")
        for key, expr in ref.items():
            f.write(f"assign mon_itf.{key} = {expr};\n")


if __name__ == "__main__":
    main()
